#!/usr/bin/env python3
"""Paper Land site build: SEO pages, share images and sitemap.

Run from the repo root after changing PRODUCTS / JOURNAL in app.js:

    python3 tools/build.py            # pages + sitemap
    python3 tools/build.py --images   # also re-render the share images (img/og/)

What it does
  * product-<id>.html   one real page per product (own URL, title, description,
                        Open Graph tags, Product structured data)
  * blog-<id>.html      one real page per blog post (old journal-<id>.html addresses redirect)
  * a "seo" block in the <head> of every page (description, canonical, share tags)
  * sitemap.xml
  * img/og/*.jpg        1200x630 share images (with --images)

Needs: pip install playwright && playwright install chromium
"""
import asyncio, datetime, html, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = 'https://paperlandco.github.io/'
SITE = 'Paper Land'
TODAY = datetime.date.today().isoformat()
FONT_DIR = os.environ.get('PL_FONT_DIR', '')          # optional: local @fontsource folder when offline
MONTHS = {m: i + 1 for i, m in enumerate('January February March April May June July August September October November December'.split())}

PAGES = {  # file -> (title, description, og image)
    'index.html': ('Enter Paper Land — notebooks designed in Adelaide',
                   'Step into Paper Land, a pixel-art island where every stop is a notebook collection. Explore Saigon Mornings and Adelaide Arvo, or skip straight to the shop.'),
    'home.html': ('Paper Land — Notebooks for slow mornings',
                  'Hardcover paper notebooks with a single word and its definition on the cover. Designed in Adelaide, inspired by Saigon mornings. Free shipping over $60.'),
    'shop.html': ('Shop paper notebooks, spiral notebooks and planners | Paper Land',
                  'A5 hardcover paper notebooks with 120gsm pages, a small spiral notebook, undated planners and gift sets. Dot grid, lined or plain. Free shipping over $60.'),
    'collections.html': ('Collections — Saigon Mornings, Adelaide Arvo and more | Paper Land',
                         'Browse Paper Land by collection: Saigon Mornings, Adelaide Arvo, Someday Studio and the Crabit Coffee Series from Vietnam.'),
    'about.html': ('Our Story — Paper Land',
                   'The story behind Paper Land: a stationery brand designed in Adelaide and inspired by the morning coffee ritual of Saigon.'),
    'blog.html': ('Blog — notebook guides and journaling ideas | Paper Land',
                  'Notebook guides from Paper Land: spiral vs hardcover, notebook paper and gsm explained, gift ideas, journaling how-tos and the stories behind our notebooks.'),
    'help.html': ('Help, shipping and contact — Paper Land',
                  'Shipping, returns, FAQs and contact details for Paper Land. Standard shipping $9.95 Australia-wide, free over $60, with 30-day returns.'),
}

esc = lambda s: html.escape(str(s), quote=True)
strip_tags = lambda s: re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', ' ', s)).strip()
read = lambda f: open(os.path.join(ROOT, f), encoding='utf-8').read()


def write(f, s):
    with open(os.path.join(ROOT, f), 'w', encoding='utf-8') as fh:
        fh.write(s)


def clip(s, n=158):
    s = strip_tags(s)
    if len(s) <= n:
        return s
    return s[:n].rsplit(' ', 1)[0].rstrip(',;:—-') + '…'


def seo_block(file, title, desc, image, kind='website', extra_meta='', ld=None):
    url = BASE + ('' if file == 'index.html' else file)
    tags = [
        f'<meta name="description" content="{esc(desc)}">',
        f'<link rel="canonical" href="{url}">',
        f'<meta property="og:site_name" content="{SITE}">',
        f'<meta property="og:locale" content="en_AU">',
        f'<meta property="og:type" content="{kind}">',
        f'<meta property="og:title" content="{esc(title)}">',
        f'<meta property="og:description" content="{esc(desc)}">',
        f'<meta property="og:url" content="{url}">',
        f'<meta property="og:image" content="{BASE}{image}">',
        '<meta property="og:image:width" content="1200">',
        '<meta property="og:image:height" content="630">',
        '<meta name="twitter:card" content="summary_large_image">',
    ]
    if extra_meta:
        tags.append(extra_meta)
    for obj in (ld or []):
        tags.append('<script type="application/ld+json">' + json.dumps(obj, ensure_ascii=False).replace('</', '<\\/') + '</script>')
    return '<!-- seo:start (generated by tools/build.py) -->\n' + '\n'.join(tags) + '\n<!-- seo:end -->'


def apply_head(page, title, block):
    """Set <title> and put the seo block right after it (replacing an older block)."""
    page = re.sub(r'\n?<!-- seo:start.*?<!-- seo:end -->', '', page, flags=re.S)
    assert page.count('<title>') == 1, 'expected one <title>'
    return re.sub(r'<title>.*?</title>', lambda m: f'<title>{esc(title)}</title>\n{block}', page, count=1, flags=re.S)


def set_between(page, start, end, inner):
    """Replace what sits between two literal markers (keeps the markers)."""
    a = page.index(start) + len(start)
    b = page.index(end, a)
    return page[:a] + inner + page[b:]


def strip_legacy(page):
    return re.sub(r'\n?<!-- legacy:start -->.*?<!-- legacy:end -->', '', page, flags=re.S)


async def extract(pw):
    b = await pw.chromium.launch()
    pg = await b.new_page()
    await pg.goto('file://' + os.path.join(ROOT, 'shop.html'))
    data = await pg.evaluate('''() => ({P: PRODUCTS, C: COLLECTIONS, J: JOURNAL,
        T: Object.fromEntries(Object.keys(PRODUCTS).map(id => [id, titleOf(id)])),
        A: Object.fromEntries(Object.keys(JOURNAL).map(k => [k, articleHTML(k)])),
        BL: blogListHTML()})''')
    await b.close()
    return data


def crumbs_ld(items):
    return {'@context': 'https://schema.org', '@type': 'BreadcrumbList', 'itemListElement': [
        {'@type': 'ListItem', 'position': i + 1, 'name': n, 'item': BASE + u} for i, (n, u) in enumerate(items)]}


def build_products(D):
    tpl = strip_legacy(read('product.html'))
    P, C, T = D['P'], D['C'], D['T']
    for pid, p in P.items():
        f = f'product-{pid}.html'
        title_txt = T[pid]
        col = C.get(p['col'])
        colname = col['name'] if col else 'Gift Sets'
        fmt = p['fmt'].split(' · ')[0]
        title = f"{title_txt} — {fmt} | {SITE}"
        if p.get('seo'):
            title = f"{p['seo']} | {SITE}"
        elif len(title) > 65:
            title = f"{title_txt} | {SITE}"
        lead = f"{p['name']} {p['ph']}, noun: {p['def']} " if p.get('def') else ''
        desc = clip(lead + p['desc'])
        image = f'img/og/{pid}.jpg'
        brand = p.get('brand') or SITE
        ld = [{'@context': 'https://schema.org', '@type': 'Product', 'name': title_txt, 'description': strip_tags(p['desc']),
               'image': [BASE + image] + [BASE + i for i in p.get('imgs', [])], 'sku': pid, 'category': 'Notebooks & Journals',
               'brand': {'@type': 'Brand', 'name': brand},
               'offers': {'@type': 'Offer', 'url': BASE + f, 'priceCurrency': 'AUD', 'price': f"{p['price']:.2f}",
                          'itemCondition': 'https://schema.org/NewCondition'}},
              crumbs_ld([('Shop', 'shop.html'), (colname, 'shop.html#' + p['col']), (title_txt, f)])]
        extra = f'<meta property="product:price:amount" content="{p["price"]:.2f}">\n<meta property="product:price:currency" content="AUD">\n<meta property="product:brand" content="{esc(brand)}">'
        page = apply_head(tpl, title, seo_block(f, title, desc, image, 'product', extra, ld))
        page = page.replace('<body data-page="product">', f'<body data-page="product" data-handle="{pid}">', 1)
        details = [f"Format: {p['fmt']}"] + ([f"Ruling: {p['ruling']}"] if p.get('ruling') else []) + ([f"Paper: {p['paper']}"] if p.get('paper') else [])
        static = (f'<div class="info"><div class="eyebrow">{esc(colname)}</div><h1>{esc(title_txt)}</h1>'
                  f'<div class="price">${p["price"]:.2f} AUD</div>'
                  + (f'<div class="defn"><small>{esc(p["name"])} · {esc(p["ph"])} · noun</small>{esc(p["def"])}</div>' if p.get('def') else '')
                  + f'<p class="desc">{p["desc"]}</p><ul>' + ''.join(f'<li>{esc(d)}</li>' for d in details) + '</ul></div>')
        page = set_between(page, '<div class="pdp" id="pdp">', '</div>\n  <div class="sec-head"', static)
        write(f, page)
    return [f'product-{pid}.html' for pid in P]


def journal_date(s):
    m = re.match(r'(\w+) (\d{4})', s)
    return f'{m.group(2)}-{MONTHS[m.group(1)]:02d}-01' if m and m.group(1) in MONTHS else TODAY


def build_journal(D):
    tpl = strip_legacy(read('article.html'))
    J = D['J']
    for k, j in J.items():
        f = f'blog-{k}.html'
        title = f"{j['title']} | {SITE}"
        desc = clip(j['lede'])
        image = f'img/og/journal-{k}.jpg'
        words = len(strip_tags(j['body']).split())
        ld = [{'@context': 'https://schema.org', '@type': 'BlogPosting', 'headline': j['title'], 'description': strip_tags(j['lede']),
               'image': [BASE + f'img/blog/{k}.jpg', BASE + image], 'datePublished': journal_date(j['date']), 'articleSection': j['cat'], 'wordCount': words,
               'inLanguage': 'en-AU', 'author': {'@type': 'Organization', 'name': SITE, 'url': BASE},
               'publisher': {'@type': 'Organization', 'name': SITE, 'url': BASE, 'logo': {'@type': 'ImageObject', 'url': BASE + 'img/logo-512.png'}},
               'mainEntityOfPage': BASE + f},
              crumbs_ld([('Blog', 'blog.html'), (j['title'], f)])]
        page = apply_head(tpl, title, seo_block(f, title, desc, image, 'article', '', ld))
        page = page.replace('<body data-page="article">', f'<body data-page="article" data-handle="{k}">', 1)
        page = set_between(page, '<article class="article" id="article">', '</article>', D['A'][k])
        write(f, page)
    return [f'blog-{k}.html' for k in J]


def build_redirects(D):
    """The blog used to be called Journal: keep the old addresses working."""
    def stub(target, title):
        return ('<!doctype html>\n<html lang="en"><head><meta charset="utf-8">\n'
                f'<title>{esc(title)}</title>\n<link rel="canonical" href="{BASE}{target}">\n<meta name="robots" content="noindex">\n'
                f'<meta http-equiv="refresh" content="0; url={target}">\n'
                f"<script>try{{sessionStorage.setItem('pl-ref',document.referrer||'')}}catch(e){{}}location.replace('{target}'+location.search+location.hash)</script>\n"
                f'</head><body><p>This page has moved to <a href="{target}">{esc(title)}</a>.</p></body></html>\n')
    write('journal.html', stub('blog.html', 'Paper Land Blog'))
    for k in ('why-saigon', 'arvo-reset', 'bullet-journal'):   # posts that were published as journal-<id>.html
        write(f'journal-{k}.html', stub(f'blog-{k}.html', D['J'][k]['title']))


def build_static(D):
    P, C, J, T = D['P'], D['C'], D['J'], D['T']
    org = {'@context': 'https://schema.org', '@graph': [
        {'@type': 'Organization', '@id': BASE + '#org', 'name': SITE, 'url': BASE, 'logo': BASE + 'img/logo-512.png',
         'description': 'Design-led stationery brand. Hardcover notebooks with a word and its definition on the cover, designed in Adelaide and inspired by Saigon.'},
        {'@type': 'WebSite', '@id': BASE + '#site', 'name': SITE, 'url': BASE, 'inLanguage': 'en-AU', 'publisher': {'@id': BASE + '#org'}}]}
    shop_ld = {'@context': 'https://schema.org', '@type': 'ItemList', 'name': 'Paper Land shop', 'itemListElement': [
        {'@type': 'ListItem', 'position': i + 1, 'name': T[pid], 'url': BASE + f'product-{pid}.html'} for i, pid in enumerate(P)]}
    for f, (title, desc) in PAGES.items():
        ld = [org] if f in ('index.html', 'home.html') else [shop_ld] if f == 'shop.html' else []
        page = apply_head(read(f), title, seo_block(f, title, desc, 'img/og/paper-land.jpg', 'website', '', ld))
        if f == 'shop.html':   # plain links so crawlers and no-JS visitors still reach every product (app.js redraws the grid)
            cards = ''.join(f'<div class="card"><a class="stage-link" href="product-{pid}.html"><h3>{esc(T[pid])}</h3></a>'
                            f'<div class="row"><span class="price">${p["price"]:.2f} AUD</span></div></div>' for pid, p in P.items())
            page = set_between(page, '<div class="grid" id="grid" style="padding-bottom:100px">', '</div>\n</section>', cards)
        if f == 'blog.html':
            page = set_between(page, '<div class="jlist" id="jlist">', '</div>\n</section>', D['BL'])
        write(f, page)
    # old hash URLs (product.html#arvo, article.html#why-saigon) forward to the new pages
    for f, prefix, ids, home in (('product.html', 'product-', list(P), 'shop.html'), ('article.html', 'blog-', list(J), 'blog.html')):
        legacy = ('<!-- legacy:start -->\n<meta name="robots" content="noindex">\n<script>(function(){var h=location.hash.slice(1),ids=' + json.dumps(ids, separators=(',', ':'))
                  + f";try{{sessionStorage.setItem('pl-ref',document.referrer||'')}}catch(e){{}}location.replace((ids.indexOf(h)>-1?'{prefix}'+h+'.html':'{home}')+location.search)}})();</script>\n<!-- legacy:end -->")
        page = strip_legacy(read(f))
        page = page.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n' + legacy, 1)
        write(f, page)


def build_sitemap(files):
    urls = ['', 'home.html', 'shop.html', 'collections.html', 'about.html', 'blog.html', 'help.html'] + files
    body = ''.join(f'  <url><loc>{BASE}{u}</loc><lastmod>{TODAY}</lastmod></url>\n' for u in urls)
    write('sitemap.xml', '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + body + '</urlset>\n')
    return len(urls)


def local_fonts():
    if not FONT_DIR:
        return ''
    f = lambda fam, pkg, w: f"@font-face{{font-family:'{fam}';font-weight:{w};src:url('file://{FONT_DIR}/{pkg}/files/{pkg}-latin-{w}-normal.woff2')}}"
    return ''.join(f('Montserrat', 'montserrat', w) for w in (300, 400, 500, 600, 700))


