async def build_images(pw, D):
    os.makedirs(os.path.join(ROOT, 'img', 'og'), exist_ok=True)
    b = await pw.chromium.launch()
    pg = await b.new_page(viewport={'width': 1200, 'height': 630})
    await pg.goto('file://' + os.path.join(ROOT, 'shop.html'))
    await pg.add_style_tag(content=local_fonts() + OG_CSS)
    brand = '<div class="brand"><b>Paper</b> Land</div>'

    async def shot(name, inner, bg, cls=''):
        await pg.evaluate('([h,bg,c])=>{document.body.className="";document.body.innerHTML=`<div class="og ${c}" style="background:${bg}">${h}</div>`}', [inner, bg, cls])
        await pg.evaluate('document.fonts.ready')
        await pg.wait_for_timeout(250)
        await pg.screenshot(path=os.path.join(ROOT, 'img', 'og', name + '.jpg'), type='jpeg', quality=86, clip={'x': 0, 'y': 0, 'width': 1200, 'height': 630})

    P, C, J, T = D['P'], D['C'], D['J'], D['T']
    for pid, p in P.items():
        col = C.get(p['col'])
        cover = await pg.evaluate('id=>cover(id)', pid)
        sub = p.get('def') or p['fmt']
        inner = (f'<div class="art"><div class="card {"photo" if p.get("imgs") else ""}"><div class="stage">{cover}</div></div></div>'
                 f'<div class="txt"><div class="eb">{esc(col["name"] if col else "Gift Sets")}</div><h1>{esc(T[pid])}</h1><p>{esc(sub)}</p></div>{brand}')
        await shot(pid, inner, col['bg'] if col else '#F4EEE4')
    for k, j in J.items():
        inner = f'<div class="txt"><div class="eb">{esc(SITE)} Journal · {esc(j["cat"])}</div><h1>{esc(j["title"])}</h1><p>{esc(strip_tags(j["lede"]))}</p></div>{brand}'
        if not os.path.exists(os.path.join(ROOT, 'img', 'blog', k + '.jpg')):   # posts with a scene use it (tools/render_blog.py)
            await shot('journal-' + k, inner, j['bg'], 'wide')
    trio = ''
    for i in ('alleyway', 'iced-coffee', 'arvo'):
        trio += '<div class="card"><div class="stage">' + await pg.evaluate('id=>cover(id)', i) + '</div></div>'
    inner = (f'<div class="art"><div class="trio">{trio}</div></div><div class="txt"><div class="eb">Designed in Adelaide</div>'
             f'<h1>Notebooks with a word on the cover.</h1><p>Hardcover notebooks, planners and pocket notes, inspired by Saigon mornings.</p></div>{brand}')
    await shot('paper-land', inner, '#F4EEE4', 'home')
    await b.close()


async def main():
    from playwright.async_api import async_playwright
    async with async_playwright() as pw:
        D = await extract(pw)
        build_static(D)
        files = build_products(D) + build_journal(D)
        build_redirects(D)
        n = build_sitemap(files)
        if '--images' in sys.argv:
            await build_images(pw, D)
    print(f'built {len(D["P"])} product pages, {len(D["J"])} blog posts, sitemap with {n} urls' + (', share images' if '--images' in sys.argv else ''))


if __name__ == '__main__':
    asyncio.run(main())
